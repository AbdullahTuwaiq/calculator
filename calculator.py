"""
برنامج الآلة الحاسبة البسيطة (Simple Calculator)
مشروع الوحدة الثالثة: From Issue to Release
"""


def add(a, b):
    """دالة لجمع عددين."""
    return a + b


def subtract(a, b):
    """دالة لطرح عددين."""
    return a - b


def multiply(a, b):
    """دالة لضرب عددين."""
    return a * b


def divide(a, b):
    """دالة لقسمة عددين مع التحقق من القسمة على صفر."""
    if b == 0:
        return "خطأ: لا يمكن القسمة على صفر!"
    return a / b


def show_menu():
    """عرض قائمة العمليات الحسابية."""
    print("\n--- الآلة الحاسبة ---")
    print("1. جمع (+)")
    print("2. طرح (-)")
    print("3. ضرب (*)")
    print("4. قسمة (/)")
    print("5. خروج")


def main():
    """الدالة الرئيسية لتشغيل الآلة الحاسبة."""
    while True:
        show_menu()
        choice = input("اختر رقم العملية (1-5): ").strip()

        if choice == "5":
            print("تم إغلاق الآلة الحاسبة. مع السلامة!")
            break

        if choice not in ["1", "2", "3", "4"]:
            print("خيار غير صحيح! الرجاء اختيار رقم من 1 إلى 5.")
            continue

        try:
            num1 = float(input("أدخل الرقم الأول: "))
            num2 = float(input("أدخل الرقم الثاني: "))
        except ValueError:
            print("خطأ: الرجاء إدخال أرقام صحيحة فقط.")
            continue

        if choice == "1":
            print(f"النتيجة: {num1} + {num2} = {add(num1, num2)}")
        elif choice == "2":
            print(f"النتيجة: {num1} - {num2} = {subtract(num1, num2)}")
        elif choice == "3":
            print(f"النتيجة: {num1} * {num2} = {multiply(num1, num2)}")
        elif choice == "4":
            result = divide(num1, num2)
            print(f"النتيجة: {result}")


if __name__ == "__main__":
    main()